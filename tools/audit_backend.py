    metadata = json.loads(jar.with_suffix(".json").read_text())
    sha256 = hashlib.sha256(jar.read_bytes()).hexdigest()
    sha1 = hashlib.sha1(jar.read_bytes()).hexdigest()
    expected = metadata["downloads"]["client"]["sha1"]
    if sha1 != expected:
        raise SystemExit("Installed client JAR does not match its manifest checksum")
